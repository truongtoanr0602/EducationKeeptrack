using EducationKeeptrack.Learning.Domain;
using Microsoft.EntityFrameworkCore;
namespace EducationKeeptrack.Learning.Infrastructure;

public sealed class LearningDatabase(DbContextOptions<LearningDatabase> options) : DbContext(options)
{
    public DbSet<Assessment> Assessments => Set<Assessment>();
    public DbSet<Submission> Submissions => Set<Submission>();
    public DbSet<SubmissionPhoto> SubmissionPhotos => Set<SubmissionPhoto>();
    public DbSet<ResultRevision> ResultRevisions => Set<ResultRevision>();
    public DbSet<ClassCurriculum> Curricula => Set<ClassCurriculum>();
    public DbSet<Skill> Skills => Set<Skill>();
    public DbSet<SkillEvent> SkillEvents => Set<SkillEvent>();
    public DbSet<AssessmentSkillSet> AssessmentSkillSets => Set<AssessmentSkillSet>();
    public DbSet<AssessmentSkill> AssessmentSkills => Set<AssessmentSkill>();
    public DbSet<SkillResult> SkillResults => Set<SkillResult>();
    public DbSet<SkillRevision> SkillRevisions => Set<SkillRevision>();
    public DbSet<ReviewPlan> ReviewPlans => Set<ReviewPlan>();
    public DbSet<PlanRevision> PlanRevisions => Set<PlanRevision>();
    public DbSet<Material> Materials => Set<Material>();
    public DbSet<MaterialRevision> MaterialRevisions => Set<MaterialRevision>();
    public DbSet<CurriculumLesson> CurriculumLessons => Set<CurriculumLesson>();
    public DbSet<LessonSessionLink> LessonSessionLinks => Set<LessonSessionLink>();
    public DbSet<Question> Questions => Set<Question>();
    public DbSet<QuestionImage> QuestionImages => Set<QuestionImage>();
    public DbSet<ExamBlueprint> ExamBlueprints => Set<ExamBlueprint>();
    public DbSet<Exam> Exams => Set<Exam>();
    public DbSet<ExamItem> ExamItems => Set<ExamItem>();
    public DbSet<ExamSeat> ExamSeats => Set<ExamSeat>();
    protected override void OnModelCreating(ModelBuilder model)
    {
        model.HasDefaultSchema("learning");
        var curriculum = model.Entity<ClassCurriculum>();
        curriculum.HasKey(x => x.Id);
        curriculum.Property(x => x.Id).ValueGeneratedNever();
        curriculum.Property(x => x.OwnerId).HasMaxLength(450);
        curriculum.Property(x => x.Subject).HasMaxLength(80);
        curriculum.Property(x => x.Grade).HasMaxLength(40);
        curriculum.Property(x => x.Term).HasMaxLength(40);
        curriculum.Property(x => x.Textbook).HasMaxLength(160);
        curriculum.Property(x => x.Version).IsConcurrencyToken();
        curriculum.HasIndex(x => new { x.OwnerId, x.ClassId }).IsUnique();
        curriculum.HasMany(x => x.Skills).WithOne().HasForeignKey(x => x.CurriculumId).OnDelete(DeleteBehavior.Restrict);
        curriculum.HasMany(x => x.Lessons).WithOne().HasForeignKey(x => x.CurriculumId).OnDelete(DeleteBehavior.Restrict);
        var skill = model.Entity<Skill>();
        skill.HasKey(x => x.Id);
        skill.Property(x => x.Id).ValueGeneratedNever();
        skill.Property(x => x.OwnerId).HasMaxLength(450);
        skill.Property(x => x.Code).HasMaxLength(20);
        skill.Property(x => x.Name).HasMaxLength(200);
        skill.Property(x => x.Strand).HasMaxLength(120);
        skill.Property(x => x.Criteria).HasMaxLength(500);
        skill.Property(x => x.Source).HasMaxLength(200);
        skill.Property(x => x.Status).HasMaxLength(20);
        skill.Property(x => x.TaughtBy).HasMaxLength(450);
        skill.Ignore(x => x.IsTaught);
        skill.HasIndex(x => new { x.OwnerId, x.ClassId });
        // Archived skills free their code; two live skills of one class never share a code.
        skill.HasIndex(x => new { x.CurriculumId, x.Code }).IsUnique().HasFilter("\"Archived\" = false");
        skill.HasMany(x => x.Events).WithOne().HasForeignKey(x => x.SkillId).OnDelete(DeleteBehavior.Restrict);
        var skillEvent = model.Entity<SkillEvent>();
        skillEvent.HasKey(x => x.Id);
        skillEvent.Property(x => x.Id).ValueGeneratedNever();
        skillEvent.Property(x => x.Action).HasMaxLength(20);
        skillEvent.Property(x => x.ActorId).HasMaxLength(450);
        skillEvent.Property(x => x.Detail).HasMaxLength(300);
        skillEvent.HasIndex(x => new { x.SkillId, x.CurriculumVersion });
        var skillSet = model.Entity<AssessmentSkillSet>();
        skillSet.HasKey(x => x.Id);
        skillSet.Property(x => x.Id).ValueGeneratedNever();
        skillSet.Property(x => x.OwnerId).HasMaxLength(450);
        skillSet.Property(x => x.Version).IsConcurrencyToken();
        skillSet.HasIndex(x => x.AssessmentId).IsUnique();
        skillSet.HasIndex(x => new { x.OwnerId, x.ClassId });
        skillSet.HasMany(x => x.Skills).WithOne().HasForeignKey(x => x.SetId).OnDelete(DeleteBehavior.Restrict);
        skillSet.HasMany(x => x.Results).WithOne().HasForeignKey(x => x.SetId).OnDelete(DeleteBehavior.Restrict);
        var assessmentSkill = model.Entity<AssessmentSkill>();
        assessmentSkill.HasKey(x => x.Id);
        assessmentSkill.Property(x => x.Id).ValueGeneratedNever();
        assessmentSkill.HasIndex(x => new { x.SetId, x.SkillId }).IsUnique();
        var skillResult = model.Entity<SkillResult>();
        skillResult.HasKey(x => x.Id);
        skillResult.Property(x => x.Id).ValueGeneratedNever();
        skillResult.Property(x => x.OwnerId).HasMaxLength(450);
        skillResult.Property(x => x.StudentName).HasMaxLength(120);
        skillResult.Property(x => x.Status).HasMaxLength(20);
        skillResult.Property(x => x.Note).HasMaxLength(500);
        skillResult.Property(x => x.Version).IsConcurrencyToken();
        skillResult.HasIndex(x => new { x.SetId, x.StudentId, x.SkillId }).IsUnique();
        skillResult.HasIndex(x => new { x.OwnerId, x.ClassId, x.StudentId });
        skillResult.HasMany(x => x.History).WithOne().HasForeignKey(x => x.ResultId).OnDelete(DeleteBehavior.Restrict);
        var skillRevision = model.Entity<SkillRevision>();
        skillRevision.HasKey(x => x.Id);
        skillRevision.Property(x => x.Id).ValueGeneratedNever();
        skillRevision.Property(x => x.Status).HasMaxLength(20);
        skillRevision.Property(x => x.Note).HasMaxLength(500);
        skillRevision.Property(x => x.Action).HasMaxLength(20);
        skillRevision.Property(x => x.ActorId).HasMaxLength(450);
        skillRevision.HasIndex(x => new { x.ResultId, x.Version }).IsUnique();
        var plan = model.Entity<ReviewPlan>();
        plan.HasKey(x => x.Id);
        plan.Property(x => x.Id).ValueGeneratedNever();
        plan.Property(x => x.OwnerId).HasMaxLength(450);
        plan.Property(x => x.Status).HasMaxLength(20);
        plan.Property(x => x.Stamp).IsConcurrencyToken();
        // Plain text, not jsonb: jsonb would reorder keys and break the unchanged-content check.
        plan.Property(x => x.ContentJson).HasColumnType("text");
        plan.Property(x => x.ApprovedContentJson).HasColumnType("text");
        plan.Property(x => x.EvidenceJson).HasColumnType("text");
        plan.HasIndex(x => new { x.OwnerId, x.ClassId, x.WeekStart }).IsUnique();
        plan.HasMany(x => x.Revisions).WithOne().HasForeignKey(x => x.PlanId).OnDelete(DeleteBehavior.Restrict);
        var planRevision = model.Entity<PlanRevision>();
        planRevision.HasKey(x => x.Id);
        planRevision.Property(x => x.Id).ValueGeneratedNever();
        planRevision.Property(x => x.Action).HasMaxLength(20);
        planRevision.Property(x => x.Status).HasMaxLength(20);
        planRevision.Property(x => x.ActorId).HasMaxLength(450);
        planRevision.Property(x => x.ContentJson).HasColumnType("text");
        planRevision.HasIndex(x => new { x.PlanId, x.Version }).IsUnique();
        var material = model.Entity<Material>();
        material.HasKey(x => x.Id);
        material.Property(x => x.Id).ValueGeneratedNever();
        material.Property(x => x.OwnerId).HasMaxLength(450);
        material.Property(x => x.Title).HasMaxLength(200);
        material.Property(x => x.Content).HasMaxLength(2000);
        material.Property(x => x.Difficulty).HasMaxLength(20);
        material.Property(x => x.Status).HasMaxLength(20);
        material.Property(x => x.Version).IsConcurrencyToken();
        material.HasIndex(x => new { x.OwnerId, x.ClassId, x.SkillId });
        material.HasMany(x => x.Revisions).WithOne().HasForeignKey(x => x.MaterialId).OnDelete(DeleteBehavior.Restrict);
        var materialRevision = model.Entity<MaterialRevision>();
        materialRevision.HasKey(x => x.Id);
        materialRevision.Property(x => x.Id).ValueGeneratedNever();
        materialRevision.Property(x => x.Action).HasMaxLength(20);
        materialRevision.Property(x => x.ActorId).HasMaxLength(450);
        materialRevision.Property(x => x.Title).HasMaxLength(200);
        materialRevision.Property(x => x.Content).HasMaxLength(2000);
        materialRevision.Property(x => x.Difficulty).HasMaxLength(20);
        materialRevision.Property(x => x.Status).HasMaxLength(20);
        materialRevision.HasIndex(x => new { x.MaterialId, x.Version }).IsUnique();
        ConfigureBank(model);
        var assessment = model.Entity<Assessment>();
        assessment.HasKey(x => x.Id);
        assessment.Property(x => x.Id).ValueGeneratedNever();
        assessment.Property(x => x.OwnerId).HasMaxLength(450);
        assessment.Property(x => x.Title).HasMaxLength(160);
        assessment.Property(x => x.DefaultMethod).HasMaxLength(20);
        assessment.Property(x => x.Rubric).HasMaxLength(5000);
        assessment.HasIndex(x => new { x.OwnerId, x.ClassId });
        assessment.HasMany(x => x.Submissions).WithOne().HasForeignKey(x => x.AssessmentId).OnDelete(DeleteBehavior.Restrict);
        var submission = model.Entity<Submission>();
        submission.HasKey(x => x.Id);
        submission.Property(x => x.Id).ValueGeneratedNever();
        submission.Property(x => x.StudentName).HasMaxLength(120);
        submission.Property(x => x.Status).HasMaxLength(20);
        submission.Property(x => x.Method).HasMaxLength(20);
        submission.Property(x => x.Version).IsConcurrencyToken();
        submission.Property(x => x.AiReasoning).HasMaxLength(2000);
        submission.Property(x => x.AiWarning).HasMaxLength(500);
        submission.Property(x => x.AiStatus).HasMaxLength(20);
        submission.HasIndex(x => new { x.AssessmentId, x.StudentId }).IsUnique();
        submission.HasMany(x => x.History).WithOne().HasForeignKey(x => x.SubmissionId).OnDelete(DeleteBehavior.Restrict);
        submission.HasMany(x => x.Photos).WithOne().HasForeignKey(x => x.SubmissionId).OnDelete(DeleteBehavior.Cascade);
        var photo = model.Entity<SubmissionPhoto>();
        photo.HasKey(x => x.Id);
        photo.Property(x => x.Id).ValueGeneratedNever();
        photo.Property(x => x.PhotoKey).HasMaxLength(300);
        photo.Property(x => x.ContentType).HasMaxLength(100);
        photo.Property(x => x.Sha256).HasMaxLength(64);
        photo.HasIndex(x => new { x.SubmissionId, x.SequenceIndex });
        var revision = model.Entity<ResultRevision>();
        revision.ToTable("ResultRevision");
        revision.HasKey(x => x.Id);
        revision.Property(x => x.Id).ValueGeneratedNever();
        revision.Property(x => x.Status).HasMaxLength(20);
        revision.Property(x => x.Method).HasMaxLength(20);
        revision.Property(x => x.Action).HasMaxLength(20);
        revision.HasIndex(x => new { x.SubmissionId, x.Version }).IsUnique();
        revision.HasIndex(x => x.DispatchedAt);
        revision.Ignore(x => x.IncludedInStatistics);
    }
    private static void ConfigureBank(ModelBuilder model)
    {
        var lesson = model.Entity<CurriculumLesson>();
        lesson.HasKey(x => x.Id);
        lesson.Property(x => x.Id).ValueGeneratedNever();
        lesson.Property(x => x.OwnerId).HasMaxLength(450);
        lesson.Property(x => x.Topic).HasMaxLength(200);
        lesson.Property(x => x.Title).HasMaxLength(300);
        lesson.Property(x => x.Knowledge).HasMaxLength(1000);
        lesson.Property(x => x.Outcomes).HasMaxLength(1000);
        lesson.Property(x => x.SkillsText).HasMaxLength(1000);
        lesson.Property(x => x.Competencies).HasMaxLength(300);
        lesson.HasIndex(x => new { x.OwnerId, x.ClassId });
        // Archived lessons free their number; two live lessons of one curriculum never share it.
        lesson.HasIndex(x => new { x.CurriculumId, x.No }).IsUnique().HasFilter("\"Archived\" = false");
        var link = model.Entity<LessonSessionLink>();
        link.HasKey(x => x.Id);
        link.Property(x => x.Id).ValueGeneratedNever();
        link.Property(x => x.OwnerId).HasMaxLength(450);
        link.HasIndex(x => new { x.OwnerId, x.ClassId });
        link.HasIndex(x => x.LessonId).IsUnique();
        var question = model.Entity<Question>();
        question.HasKey(x => x.Id);
        question.Property(x => x.Id).ValueGeneratedNever();
        question.Property(x => x.OwnerId).HasMaxLength(450);
        question.Property(x => x.Code).HasMaxLength(40);
        question.Property(x => x.Type).HasMaxLength(20);
        question.Property(x => x.Level).HasMaxLength(20);
        question.Property(x => x.Stem).HasMaxLength(2000);
        question.Property(x => x.StemImage).HasMaxLength(200);
        question.Property(x => x.Points).HasColumnType("numeric(5,2)").HasDefaultValue(1m);
        question.Property(x => x.FillMode).HasMaxLength(10).HasDefaultValue("chips");
        question.Property(x => x.IgnoreDiacritics).HasDefaultValue(false);
        question.Property(x => x.SampleAnswer).HasMaxLength(2000);
        question.Property(x => x.StemHtml).HasColumnType("text");
        question.Property(x => x.AudioFile).HasMaxLength(200);
        question.Property(x => x.OptionsJson).HasColumnType("text");
        question.Property(x => x.AnswerJson).HasColumnType("text");
        question.Property(x => x.Status).HasMaxLength(20);
        question.Property(x => x.Version).IsConcurrencyToken();
        question.Ignore(x => x.Options);
        question.Ignore(x => x.Answer);
        question.HasIndex(x => new { x.OwnerId, x.ClassId, x.Code }).IsUnique();
        var image = model.Entity<QuestionImage>();
        image.HasKey(x => x.Id);
        image.Property(x => x.Id).ValueGeneratedNever();
        image.Property(x => x.OwnerId).HasMaxLength(450);
        image.Property(x => x.FileName).HasMaxLength(200);
        image.Property(x => x.NormalizedName).HasMaxLength(200);
        image.Property(x => x.StorageKey).HasMaxLength(300);
        image.Property(x => x.ContentType).HasMaxLength(100);
        image.Property(x => x.Sha256).HasMaxLength(64);
        image.HasIndex(x => new { x.OwnerId, x.ClassId, x.NormalizedName }).IsUnique();
        var blueprint = model.Entity<ExamBlueprint>();
        blueprint.HasKey(x => x.Id);
        blueprint.Property(x => x.Id).ValueGeneratedNever();
        blueprint.Property(x => x.OwnerId).HasMaxLength(450);
        blueprint.Property(x => x.Name).HasMaxLength(120);
        blueprint.HasIndex(x => new { x.OwnerId, x.ClassId, x.Name }).IsUnique();
        var exam = model.Entity<Exam>();
        exam.HasKey(x => x.Id);
        exam.Property(x => x.Id).ValueGeneratedNever();
        exam.Property(x => x.OwnerId).HasMaxLength(450);
        exam.Property(x => x.Title).HasMaxLength(160);
        exam.Property(x => x.Kind).HasMaxLength(20);
        exam.Property(x => x.Status).HasMaxLength(20);
        exam.Property(x => x.PublicToken).HasMaxLength(64);
        exam.Property(x => x.Version).IsConcurrencyToken();
        exam.Ignore(x => x.Scope);
        exam.HasIndex(x => new { x.OwnerId, x.ClassId });
        exam.HasIndex(x => x.PublicToken).IsUnique();
        exam.HasIndex(x => x.AssessmentId);
        exam.HasMany(x => x.Items).WithOne().HasForeignKey(x => x.ExamId).OnDelete(DeleteBehavior.Restrict);
        exam.HasMany(x => x.Seats).WithOne().HasForeignKey(x => x.ExamId).OnDelete(DeleteBehavior.Restrict);
        var item = model.Entity<ExamItem>();
        item.HasKey(x => x.Id);
        item.Property(x => x.Id).ValueGeneratedNever();
        item.Property(x => x.Level).HasMaxLength(20);
        item.Property(x => x.SnapshotJson).HasColumnType("text");
        item.Ignore(x => x.Snapshot);
        item.HasIndex(x => new { x.ExamId, x.SeatId, x.Order });
        var seat = model.Entity<ExamSeat>();
        seat.HasKey(x => x.Id);
        seat.Property(x => x.Id).ValueGeneratedNever();
        seat.Property(x => x.StudentName).HasMaxLength(120);
        seat.Property(x => x.Code).HasMaxLength(10);
        seat.Property(x => x.AttemptStatus).HasMaxLength(20);
        seat.Property(x => x.Nonce).HasMaxLength(64);
        seat.Property(x => x.AnswersJson).HasColumnType("text");
        seat.Property(x => x.Score).HasColumnType("numeric(7,2)").HasDefaultValue(0m);
        seat.Property(x => x.ManualJson).HasColumnType("text").HasDefaultValue("{}");
        seat.Ignore(x => x.Grades);
        seat.Property(x => x.PendingEssays).HasDefaultValue(0);
        seat.Property(x => x.Version).IsConcurrencyToken();
        seat.Ignore(x => x.Answers);
        seat.HasIndex(x => new { x.ExamId, x.StudentId }).IsUnique();
    }
}
