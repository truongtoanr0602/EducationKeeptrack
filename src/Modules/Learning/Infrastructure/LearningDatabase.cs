using EducationKeeptrack.Learning.Domain;
using Microsoft.EntityFrameworkCore;
namespace EducationKeeptrack.Learning.Infrastructure;

public sealed class LearningDatabase(DbContextOptions<LearningDatabase> options) : DbContext(options)
{
    public DbSet<Assessment> Assessments => Set<Assessment>();
    public DbSet<Submission> Submissions => Set<Submission>();
    public DbSet<ResultRevision> ResultRevisions => Set<ResultRevision>();
    public DbSet<ClassCurriculum> Curricula => Set<ClassCurriculum>();
    public DbSet<Skill> Skills => Set<Skill>();
    public DbSet<SkillEvent> SkillEvents => Set<SkillEvent>();
    public DbSet<Material> Materials => Set<Material>();
    public DbSet<MaterialRevision> MaterialRevisions => Set<MaterialRevision>();
    protected override void OnModelCreating(ModelBuilder model)
    {
        model.HasDefaultSchema("learning");
        var curriculum = model.Entity<ClassCurriculum>();
        curriculum.HasKey(x => x.Id);
        curriculum.Property(x => x.Id).ValueGeneratedNever();
        curriculum.Property(x => x.OwnerId).HasMaxLength(450);
        curriculum.Property(x => x.Subject).HasMaxLength(80);
        curriculum.Property(x => x.Grade).HasMaxLength(40);
        curriculum.Property(x => x.Term).HasMaxLength(40);
        curriculum.Property(x => x.Textbook).HasMaxLength(160);
        curriculum.Property(x => x.Version).IsConcurrencyToken();
        curriculum.HasIndex(x => new { x.OwnerId, x.ClassId }).IsUnique();
        curriculum.HasMany(x => x.Skills).WithOne().HasForeignKey(x => x.CurriculumId).OnDelete(DeleteBehavior.Restrict);
        var skill = model.Entity<Skill>();
        skill.HasKey(x => x.Id);
        skill.Property(x => x.Id).ValueGeneratedNever();
        skill.Property(x => x.OwnerId).HasMaxLength(450);
        skill.Property(x => x.Code).HasMaxLength(20);
        skill.Property(x => x.Name).HasMaxLength(200);
        skill.Property(x => x.Strand).HasMaxLength(120);
        skill.Property(x => x.Criteria).HasMaxLength(500);
        skill.Property(x => x.Source).HasMaxLength(200);
        skill.Property(x => x.Status).HasMaxLength(20);
        skill.Property(x => x.TaughtBy).HasMaxLength(450);
        skill.Ignore(x => x.IsTaught);
        skill.HasIndex(x => new { x.OwnerId, x.ClassId });
        // Archived skills free their code; two live skills of one class never share a code.
        skill.HasIndex(x => new { x.CurriculumId, x.Code }).IsUnique().HasFilter("\"Archived\" = false");
        skill.HasMany(x => x.Events).WithOne().HasForeignKey(x => x.SkillId).OnDelete(DeleteBehavior.Restrict);
        var skillEvent = model.Entity<SkillEvent>();
        skillEvent.HasKey(x => x.Id);
        skillEvent.Property(x => x.Id).ValueGeneratedNever();
        skillEvent.Property(x => x.Action).HasMaxLength(20);
        skillEvent.Property(x => x.ActorId).HasMaxLength(450);
        skillEvent.Property(x => x.Detail).HasMaxLength(300);
        skillEvent.HasIndex(x => new { x.SkillId, x.CurriculumVersion });
        var material = model.Entity<Material>();
        material.HasKey(x => x.Id);
        material.Property(x => x.Id).ValueGeneratedNever();
        material.Property(x => x.OwnerId).HasMaxLength(450);
        material.Property(x => x.Title).HasMaxLength(200);
        material.Property(x => x.Content).HasMaxLength(2000);
        material.Property(x => x.Difficulty).HasMaxLength(20);
        material.Property(x => x.Status).HasMaxLength(20);
        material.Property(x => x.Version).IsConcurrencyToken();
        material.HasIndex(x => new { x.OwnerId, x.ClassId, x.SkillId });
        material.HasMany(x => x.Revisions).WithOne().HasForeignKey(x => x.MaterialId).OnDelete(DeleteBehavior.Restrict);
        var materialRevision = model.Entity<MaterialRevision>();
        materialRevision.HasKey(x => x.Id);
        materialRevision.Property(x => x.Id).ValueGeneratedNever();
        materialRevision.Property(x => x.Action).HasMaxLength(20);
        materialRevision.Property(x => x.ActorId).HasMaxLength(450);
        materialRevision.Property(x => x.Title).HasMaxLength(200);
        materialRevision.Property(x => x.Content).HasMaxLength(2000);
        materialRevision.Property(x => x.Difficulty).HasMaxLength(20);
        materialRevision.Property(x => x.Status).HasMaxLength(20);
        materialRevision.HasIndex(x => new { x.MaterialId, x.Version }).IsUnique();
        var assessment = model.Entity<Assessment>();
        assessment.HasKey(x => x.Id);
        assessment.Property(x => x.Id).ValueGeneratedNever();
        assessment.Property(x => x.OwnerId).HasMaxLength(450);
        assessment.Property(x => x.Title).HasMaxLength(160);
        assessment.Property(x => x.DefaultMethod).HasMaxLength(20);
        assessment.HasIndex(x => new { x.OwnerId, x.ClassId });
        assessment.HasMany(x => x.Submissions).WithOne().HasForeignKey(x => x.AssessmentId).OnDelete(DeleteBehavior.Restrict);
        var submission = model.Entity<Submission>();
        submission.HasKey(x => x.Id);
        submission.Property(x => x.Id).ValueGeneratedNever();
        submission.Property(x => x.StudentName).HasMaxLength(120);
        submission.Property(x => x.Status).HasMaxLength(20);
        submission.Property(x => x.Method).HasMaxLength(20);
        submission.Property(x => x.Version).IsConcurrencyToken();
        submission.HasIndex(x => new { x.AssessmentId, x.StudentId }).IsUnique();
        submission.HasMany(x => x.History).WithOne().HasForeignKey(x => x.SubmissionId).OnDelete(DeleteBehavior.Restrict);
        var revision = model.Entity<ResultRevision>();
        revision.ToTable("ResultRevision");
        revision.HasKey(x => x.Id);
        revision.Property(x => x.Id).ValueGeneratedNever();
        revision.Property(x => x.Status).HasMaxLength(20);
        revision.Property(x => x.Method).HasMaxLength(20);
        revision.Property(x => x.Action).HasMaxLength(20);
        revision.HasIndex(x => new { x.SubmissionId, x.Version }).IsUnique();
        revision.HasIndex(x => x.DispatchedAt);
        revision.Ignore(x => x.IncludedInStatistics);
    }
}
